/**
 * Renders a still of every 3D scene into public/fallback/<scene>.webp.
 * These stills replace the live canvas under reduced motion, on low-power
 * devices and without WebGL.
 *
 * Usage (with the site running, e.g. `npm run build && npm start`):
 *   npx -y -p playwright@1.56.1 node scripts/render-fallbacks.mjs [http://localhost:3000]
 * If Playwright's browser is missing, run `npx playwright install chromium` once.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import sharp from "sharp";

const require = createRequire(import.meta.url);
const { chromium } = require("playwright");

const base = process.argv[2] || "http://localhost:3000";
const outDir = path.join(process.cwd(), "public", "fallback");
await mkdir(outDir, { recursive: true });

const browser = await chromium.launch({
  args: ["--enable-unsafe-swiftshader", "--use-angle=swiftshader", "--ignore-gpu-blocklist"],
});
// Reduced motion keeps the layout static (no pinning, no smooth scroll); ?3d=still runs the canvas with frozen poses.
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 2, reducedMotion: "reduce" });
await page.goto(`${base}/?3d=still`, { waitUntil: "networkidle" });
await page.waitForFunction(() => document.querySelector("canvas"), null, { timeout: 30000 });
await page.waitForTimeout(1500);

// Hide everything but the canvas so the stills have transparent backgrounds.
await page.addStyleTag({
  content: `
    *:not(canvas) { background: transparent !important; border-color: transparent !important; box-shadow: none !important; color: transparent !important; }
    img, svg, p, h1, h2, h3, li, label, input, select, button, a, header, footer { visibility: hidden !important; }
    html, body { background: transparent !important; }
  `,
});

const scenes = await page.$$eval("[data-scene]", (els) => els.map((e) => e.getAttribute("data-scene")));
for (const scene of scenes) {
  const slot = page.locator(`[data-scene="${scene}"]`);
  await slot.evaluate((el) => el.scrollIntoView({ block: "center" }));
  if (scene === "hero") await page.evaluate(() => window.scrollTo(0, 0));
  await page.waitForTimeout(2500);
  const box = await slot.boundingBox();
  if (!box || box.width === 0) continue;
  const clip = { x: Math.max(0, box.x), y: Math.max(0, box.y), width: Math.min(box.width, 1440), height: Math.min(box.height, 1000 - Math.max(0, box.y)) };
  const png = await page.screenshot({ clip, omitBackground: true });
  const file = path.join(outDir, `${scene}.webp`);
  await sharp(png).webp({ quality: 82, alphaQuality: 90, effort: 6 }).toFile(file);
  console.log(`${scene}: ${Math.round(clip.width)}×${Math.round(clip.height)} → ${path.relative(process.cwd(), file)}`);
}
await browser.close();

// Tiny inline copy of the hero still: it paints with the first frame (blur-up),
// so the above-the-fold still never delays Largest Contentful Paint.
const tiny = await sharp(path.join(outDir, "hero.webp")).resize({ width: 56 }).webp({ quality: 60, alphaQuality: 70 }).toBuffer();
await writeFile(
  path.join(process.cwd(), "components", "three", "heroPlaceholder.ts"),
  `// Generated by scripts/render-fallbacks.mjs. Do not edit.\nexport const heroPlaceholder =\n  "data:image/webp;base64,${tiny.toString("base64")}";\n`,
);
console.log(`hero placeholder: ${tiny.length} bytes → components/three/heroPlaceholder.ts`);
